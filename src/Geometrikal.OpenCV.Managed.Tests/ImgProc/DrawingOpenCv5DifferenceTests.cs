    public static IEnumerable<object[]> Cases()
    {
        yield return new object[] { "line_clip_thick_l8", LineClipThickL8 };
        yield return new object[] { "circle_ellipsex_line4_r7", CircleEllipsexLine4R7 };
        yield return new object[] { "circle_ellipsex_shift2_r5", CircleEllipsexShift2R5 };
        yield return new object[] { "ellipse_ellipsex_a0_t1", EllipseEllipsexA0T1 };
        yield return new object[] { "ellipse_ellipsex_a30_t1", EllipseEllipsexA30T1 };
    }

    [Theory]
    [MemberData(nameof(Cases))]
    public void SuspectCase_MatchesPinnedOpenCv5Output(string caseName, string pinnedBase64)
    {
        DrawingGoldenTests.DrawingCase c = DrawingGoldenTests.AllCases[caseName];

        Assert.True(c.Suspect, $"case '{caseName}' is expected to be flagged suspect");

        byte[] actual = DrawingGoldenTests.RenderActualBytes(caseName);
        byte[] pinned = System.Convert.FromBase64String(pinnedBase64);
        byte[] legacy = System.Convert.FromBase64String(c.Expected);

        // The port must reproduce OpenCV 5 exactly...
        Assert.Equal(pinned, actual);

        // ...and the divergence from the cv2 4.5.5 golden must actually exist;
        // if these become equal the case no longer needs the suspect flag.
        Assert.NotEqual(legacy, pinned);
    }
