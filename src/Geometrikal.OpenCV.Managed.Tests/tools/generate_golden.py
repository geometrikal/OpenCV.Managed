#!/usr/bin/env python3
"""Golden-data generator for the managed findContours port.

Runs the reference OpenCV (cv2 4.5.5) findContours over a battery of small
analytic shapes and seeded random binaries, then writes the inputs and the
reference outputs to ``TestData/contours_golden.json``. The managed C# runner
(``ImgProc/ContoursGoldenTests.cs``) reads the SAME file and asserts exact
equality of contour points and hierarchy.

Regenerate with:
    python tools/generate_golden.py
(run from the ``Geometrikal.OpenCV.Managed.Tests`` directory).

See ``tools/README.md`` for details.

OpenCV / cv2 is licensed under the Apache License 2.0.
"""

import json
import os
import sys

import cv2
import numpy as np

# ---------------------------------------------------------------------------
# OpenCV enum integer values (these match the managed C# enum values exactly:
#   RetrievalMode:  External=0 List=1 ConnectedComponents=2 Tree=3
#   ContourApproximationMode: None=1 Simple=2 Tc89L1=3 Tc89KCos=4
# ---------------------------------------------------------------------------
MODES = {
    "external": cv2.RETR_EXTERNAL,          # 0
    "list": cv2.RETR_LIST,                  # 1
    "ccomp": cv2.RETR_CCOMP,                # 2
    "tree": cv2.RETR_TREE,                  # 3
}
METHODS = {
    "none": cv2.CHAIN_APPROX_NONE,          # 1
    "simple": cv2.CHAIN_APPROX_SIMPLE,      # 2
    "tc89l1": cv2.CHAIN_APPROX_TC89_L1,     # 3
    "tc89kcos": cv2.CHAIN_APPROX_TC89_KCOS, # 4
}

ALL_MODES = list(MODES.items())
ALL_METHODS = list(METHODS.items())

# ---------------------------------------------------------------------------
# Adjudicated golden conflicts.
#
# These cases were generated by cv2 4.5.5 (the legacy TC89 implementation) but
# the managed library ports OpenCV 5's rewritten contours_approx.cpp, which is
# a deliberate behavioural difference for a single contour. They are flagged
# "suspect" so the data-driven golden runner excludes them from exact-equality
# assertions; the difference itself is covered exhaustively by
# ImgProc/ContoursOpenCv5DifferenceTests.cs. Do NOT add entries here without a
# recorded adjudication.
# ---------------------------------------------------------------------------
SUSPECT_CASES = {
    "rand_64_p50_list_tc89l1": (
        "cv2 4.5.5 legacy TC89_L1 differs from OpenCV 5 contours_approx.cpp "
        "calc_new_start push_back path for one contour (adjudicated "
        "2026-07-27; see ContoursOpenCv5DifferenceTests)."
    ),
    "rand_64_p50_tree_tc89l1": (
        "cv2 4.5.5 legacy TC89_L1 differs from OpenCV 5 contours_approx.cpp "
        "calc_new_start push_back path for one contour (adjudicated "
        "2026-07-27; see ContoursOpenCv5DifferenceTests)."
    ),
}


def arr_to_rows(arr):
    """Convert a 0/1 (or 0/nonzero) uint8 array into a list of '0'/'1' strings."""
    return ["".join("1" if v else "0" for v in row) for row in arr]


class Battery:
    def __init__(self):
        self.cases = []

    def add(self, img_name, arr, modes, methods, offsets=((0, 0),)):
        """Add one case per (mode, method, offset) combination for a binary image.

        ``arr`` is a 2D uint8 array of 0/1 values. It is stored as '0'/'1'
        rows and fed to cv2.findContours as (arr * 255).
        """
        arr = np.ascontiguousarray(arr, dtype=np.uint8)
        rows = arr_to_rows(arr)
        h, w = arr.shape
        src = (arr * 255).astype(np.uint8)
        for mode_name, mode_val in modes:
            for method_name, method_val in methods:
                for (ox, oy) in offsets:
                    # cv2 must not see our stored buffer mutated across calls.
                    contours, hierarchy = cv2.findContours(
                        src.copy(), mode_val, method_val, offset=(ox, oy)
                    )
                    c_out = [c[:, 0, :].tolist() for c in contours]
                    if hierarchy is None:
                        h_out = []
                    else:
                        h_out = hierarchy[0].tolist()
                    assert len(c_out) == len(h_out), (
                        f"{img_name}: contour/hierarchy length mismatch"
                    )
                    name = f"{img_name}_{mode_name}_{method_name}"
                    if ox != 0 or oy != 0:
                        name += f"_off{ox}_{oy}"
                    case = {
                        "name": name,
                        "width": w,
                        "height": h,
                        "rows": rows,
                        "mode": int(mode_val),
                        "method": int(method_val),
                        "offsetX": int(ox),
                        "offsetY": int(oy),
                        "contours": c_out,
                        "hierarchy": h_out,
                        "suspect": name in SUSPECT_CASES,
                    }
                    if name in SUSPECT_CASES:
                        case["suspectReason"] = SUSPECT_CASES[name]
                    self.cases.append(case)


# ---------------------------------------------------------------------------
# Image constructors (each returns a 0/1 uint8 array)
# ---------------------------------------------------------------------------

def img_all_zero(n=8):
    return np.zeros((n, n), np.uint8)


def img_single_center(n=5):
    a = np.zeros((n, n), np.uint8)
    a[n // 2, n // 2] = 1
    return a


def img_single_corner(n=5):
    a = np.zeros((n, n), np.uint8)
    a[0, 0] = 1
    return a


def img_block_2x2():
    a = np.zeros((6, 6), np.uint8)
    a[2:4, 2:4] = 1
    return a


def img_solid_rect():
    # solid 6x4 rectangle inside a 10x8 image
    a = np.zeros((8, 10), np.uint8)
    a[2:6, 2:8] = 1  # height 4 rows (2..5), width 6 cols (2..7)
    return a


def img_solid_3x3():
    # solid 3x3 with top-left at (1,1) in a 5x5 image (basic-test reference)
    a = np.zeros((5, 5), np.uint8)
    a[1:4, 1:4] = 1
    return a


def img_hollow_rect(n=10):
    # 1px-thick hollow rectangle outline inside an n x n image
    a = np.zeros((n, n), np.uint8)
    cv2.rectangle(a, (1, 1), (n - 2, n - 2), 1, 1)
    return a


def img_triple_hollow(n=16):
    # three nested 1px hollow squares -> a 3-level hierarchy
    a = np.zeros((n, n), np.uint8)
    cv2.rectangle(a, (1, 1), (14, 14), 1, 1)
    cv2.rectangle(a, (4, 4), (11, 11), 1, 1)
    cv2.rectangle(a, (6, 6), (9, 9), 1, 1)
    return a


def img_two_blobs():
    a = np.zeros((10, 16), np.uint8)
    a[2:5, 2:5] = 1
    a[5:8, 10:14] = 1
    return a


def img_diagonal_pixels(n=8):
    a = np.zeros((n, n), np.uint8)
    for i in range(n):
        a[i, i] = 1
    return a


def img_l_shape(n=8):
    # L touching all four borders: full left column + full bottom row
    a = np.zeros((n, n), np.uint8)
    a[:, 0] = 1
    a[n - 1, :] = 1
    return a


def img_full(n=6):
    return np.ones((n, n), np.uint8)


def img_row_1x8():
    # 8 wide, 1 tall, with a run of foreground
    a = np.zeros((1, 8), np.uint8)
    a[0, 2:6] = 1
    return a


def img_col_8x1():
    # 1 wide, 8 tall, with a run of foreground
    a = np.zeros((8, 1), np.uint8)
    a[2:6, 0] = 1
    return a


def img_hline(n=8):
    a = np.zeros((n, n), np.uint8)
    a[n // 2, 1:n - 1] = 1
    return a


def img_vline(n=8):
    a = np.zeros((n, n), np.uint8)
    a[1:n - 1, n // 2] = 1
    return a


def rand_img(h, w, p):
    return (np.random.rand(h, w) < p).astype(np.uint8)


# ---------------------------------------------------------------------------
# Build the battery
# ---------------------------------------------------------------------------

def build():
    b = Battery()

    # -- Small analytic shapes: ALL 4 modes x ALL 4 methods -----------------
    analytic = [
        ("all_zero_8x8", img_all_zero(8)),
        ("single_center_5x5", img_single_center(5)),
        ("single_corner_5x5", img_single_corner(5)),
        ("block_2x2", img_block_2x2()),
        ("solid_rect_6x4", img_solid_rect()),
        ("solid_3x3", img_solid_3x3()),
        ("hollow_rect_10x10", img_hollow_rect(10)),
        ("triple_hollow_16x16", img_triple_hollow(16)),
        ("two_blobs", img_two_blobs()),
        ("diagonal_pixels_8x8", img_diagonal_pixels(8)),
        ("l_shape_8x8", img_l_shape(8)),
        ("full_6x6", img_full(6)),
        ("row_1x8", img_row_1x8()),
        ("col_8x1", img_col_8x1()),
        ("hline_8x8", img_hline(8)),
        ("vline_8x8", img_vline(8)),
    ]
    for name, arr in analytic:
        b.add(name, arr, ALL_MODES, ALL_METHODS)

    # -- Seeded random binaries ---------------------------------------------
    # Random matrix: all 4 modes x {None, Simple}, plus Tree/List x {Tc89L1,Tc89KCos}.
    rand_methods_core = [("none", METHODS["none"]), ("simple", METHODS["simple"])]
    rand_modes_tc89 = [("tree", MODES["tree"]), ("list", MODES["list"])]
    rand_methods_tc89 = [("tc89l1", METHODS["tc89l1"]), ("tc89kcos", METHODS["tc89kcos"])]

    def add_random(name, arr):
        b.add(name, arr, ALL_MODES, rand_methods_core)
        b.add(name, arr, rand_modes_tc89, rand_methods_tc89)

    np.random.seed(42)
    add_random("rand_16_p30", rand_img(16, 16, 0.3))
    add_random("rand_16_p50", rand_img(16, 16, 0.5))
    add_random("rand_16_p70", rand_img(16, 16, 0.7))
    add_random("rand_32_p40", rand_img(32, 32, 0.4))
    add_random("rand_32_p60", rand_img(32, 32, 0.6))
    np.random.seed(7)
    add_random("rand_64_p50", rand_img(64, 64, 0.5))

    # -- Offset cases -------------------------------------------------------
    # hollow rect + a random 16x16, offset (5, -3), for Tree/Simple and List/None.
    off = [(5, -3)]
    hollow = img_hollow_rect(10)
    np.random.seed(123)
    rand_off = rand_img(16, 16, 0.5)
    off_tree_simple = [("tree", MODES["tree"])], [("simple", METHODS["simple"])]
    off_list_none = [("list", MODES["list"])], [("none", METHODS["none"])]
    b.add("hollow_rect_10x10", hollow, off_tree_simple[0], off_tree_simple[1], offsets=off)
    b.add("hollow_rect_10x10", hollow, off_list_none[0], off_list_none[1], offsets=off)
    b.add("rand_off_16", rand_off, off_tree_simple[0], off_tree_simple[1], offsets=off)
    b.add("rand_off_16", rand_off, off_list_none[0], off_list_none[1], offsets=off)

    return b


def sanity_checks(b):
    """A few analytic asserts so a broken cv2 install fails loudly here."""
    by_name = {c["name"]: c for c in b.cases}

    # all-zero -> no contours in every mode/method
    for (mn, _), (met, _) in [((m, 0), (me, 0)) for m in MODES for me in METHODS]:
        c = by_name[f"all_zero_8x8_{mn}_{met}"]
        assert len(c["contours"]) == 0, f"all_zero should be empty ({mn}/{met})"

    # single center pixel -> exactly one contour of one point at (2,2)
    c = by_name["single_center_5x5_external_none"]
    assert len(c["contours"]) == 1 and c["contours"][0] == [[2, 2]], c["contours"]
    assert c["hierarchy"][0] == [-1, -1, -1, -1], c["hierarchy"]

    # solid 3x3 at (1,1), External/None -> the analytic 8-point border sequence
    c = by_name["solid_3x3_external_none"]
    expected = [[1, 1], [1, 2], [1, 3], [2, 3], [3, 3], [3, 2], [3, 1], [2, 1]]
    assert c["contours"][0] == expected, (
        "solid_3x3 external/none border sequence changed: %r" % (c["contours"][0],)
    )

    # hollow rect: 2 contours for LIST/CCOMP/TREE, 1 for EXTERNAL
    assert len(by_name["hollow_rect_10x10_external_simple"]["contours"]) == 1
    assert len(by_name["hollow_rect_10x10_tree_simple"]["contours"]) == 2

    # triple hollow, TREE: three 1px rings -> outer+inner contour each = 6.
    c = by_name["triple_hollow_16x16_tree_simple"]
    assert len(c["contours"]) == 6, len(c["contours"])
    # EXTERNAL sees only the single outermost ring boundary.
    assert len(by_name["triple_hollow_16x16_external_simple"]["contours"]) == 1

    print("sanity checks passed")


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out_dir = os.path.normpath(os.path.join(here, "..", "TestData"))
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, "contours_golden.json")

    b = build()
    sanity_checks(b)

    data = {"cases": b.cases}
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(data, f, separators=(",", ":"))

    size = os.path.getsize(out_path)
    names = [c["name"] for c in b.cases]
    assert len(names) == len(set(names)), "duplicate case names!"
    print(f"wrote {len(b.cases)} cases to {out_path}")
    print(f"file size: {size} bytes ({size / 1024:.1f} KiB)")
    if size > 2 * 1024 * 1024:
        print("WARNING: golden file exceeds 2 MiB", file=sys.stderr)


if __name__ == "__main__":
    main()
